import { test } from "node:test";
import assert from "node:assert/strict";
import { fresh, ProjectManager } from "../src/game";
import { tutorialStep } from "../src/tutorial";
test("新玩家先理解居民身分，然後調查與提出第一項政見", () => {
  const s = fresh();
  assert.equal(tutorialStep(s).id, "welcome");
  s.tutorialStarted = true;
  assert.equal(tutorialStep(s).action, "issue:park");
  s.discovered.push("park");
  assert.equal(tutorialStep(s).target, "promise:1");
  s.promises.park = 1;
  assert.equal(tutorialStep(s).action, "issue:parking");
});
test("依舊存檔進度指引參選、敗選準備，不修改遊戲狀態", () => {
  const s = fresh();
  s.tutorialStarted = true;
  s.discovered = ["park", "light", "drain"];
  s.promises = { park: 1, light: 1, drain: 1 };
  s.talked = [0, 1, 2, 3];
  assert.equal(tutorialStep(s).id, "elect");
  delete s.tutorialStarted;
  assert.equal(tutorialStep(s).id, "elect");
  s.nextElection = 8;
  assert.equal(tutorialStep(s).id, "retry");
  s.day = 8;
  s.cp = 20;
  assert.equal(tutorialStep(s).id, "retry");
  s.cp = 40;
  const snapshot = JSON.stringify(s);
  assert.equal(tutorialStep(s).id, "elect");
  assert.equal(JSON.stringify(s), snapshot);
});
test("工程每一階段、事件及完工都有對應指引", () => {
  const s = fresh();
  s.tutorialStarted = true;
  s.elected = true;
  s.discovered = ["park"];
  s.promises = { park: 1 };
  assert.equal(tutorialStep(s).id, "plan");
  ProjectManager.plan(s, "park", 1, 2, 1);
  assert.equal(tutorialStep(s).target, "advance:park");
  s.projects[0].stage = 4;
  assert.equal(tutorialStep(s).action, "accelerate");
  s.event = { id: "park", type: 1 };
  assert.equal(tutorialStep(s).target, "event:paid");
  s.event = null;
  s.projects[0].stage = 5;
  assert.match(tutorialStep(s).text, /辦理驗收/);
  s.projects[0].stage = 6;
  assert.match(tutorialStep(s).text, /公布成效/);
  s.projects[0].stage = 7;
  assert.equal(tutorialStep(s).id, "done");
});
